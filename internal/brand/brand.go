// Package brand is the single source of truth for the project name and every
// identifier derived from it. Nothing else in the code base may hard-code the
// name.
package brand

import "strings"

// Name is the project name.
const Name = "tenet"

// TagKey is the struct tag key used for entity mapping, e.g. `tenet:"column:email"`.
const TagKey = Name

// CLIName is the name of the global command line tool.
const CLIName = Name

// MigrationsTable is the default table that stores executed migration versions.
const MigrationsTable = Name + "_migrations"

// MigrationLocksTable is the default table used to serialize migration runs.
const MigrationLocksTable = Name + "_migration_locks"

// GeneratedSuffix is the file suffix of generated Go files.
const GeneratedSuffix = "_" + Name + ".go"

// ConfigFile is the default configuration file name.
const ConfigFile = Name + ".yaml"

// GeneratedHeader marks generated files (see https://go.dev/s/generatedcode).
const GeneratedHeader = "// Code generated by " + Name + ". DO NOT EDIT."

// EnvPrefix is the prefix for environment variables, e.g. TENET_DATABASE_URL.
var EnvPrefix = strings.ToUpper(Name) + "_"

// Env returns the full environment variable name for key.
func Env(key string) string { return EnvPrefix + strings.ToUpper(key) }
