package schema

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/smatify/tenet/dialect"
	"github.com/smatify/tenet/types"
)

// DDL generates schema statements for a dialect.
type DDL struct {
	d     dialect.Dialect
	types *types.Registry
}

// NewDDL returns a DDL generator for d using the default type registry.
func NewDDL(d dialect.Dialect) *DDL { return &DDL{d: d, types: types.Default} }

// WithTypes returns a copy using a custom type registry.
func (g *DDL) WithTypes(r *types.Registry) *DDL { c := *g; c.types = r; return &c }

func (g *DDL) name() dialect.Name    { return g.d.Name() }
func (g *DDL) q(ident string) string { return g.d.QuoteIdent(ident) }

func (g *DDL) isMySQL() bool { return g.name() == dialect.MySQL || g.name() == dialect.MariaDB }

func (g *DDL) qList(cols []string) string {
	out := make([]string, len(cols))
	for i, c := range cols {
		out[i] = g.q(c)
	}
	return strings.Join(out, ", ")
}

// TypeDeclaration returns the SQL type of a column.
func (g *DDL) TypeDeclaration(c *Column) (string, error) {
	if c.RawType != "" {
		return c.RawType, nil
	}
	t, ok := g.types.Lookup(c.Type)
	if !ok {
		return "", fmt.Errorf("schema: column %q has unknown type %q", c.Name, c.Type)
	}
	return t.SQLDeclaration(g.name(), c.Options), nil
}

// sqliteRowID reports whether c becomes SQLite's INTEGER PRIMARY KEY rowid alias.
func (g *DDL) sqliteRowID(t *Table, c *Column) bool {
	return g.name() == dialect.SQLite && c.AutoIncrement && t.PrimaryKey != nil &&
		len(t.PrimaryKey.Columns) == 1 && strings.EqualFold(t.PrimaryKey.Columns[0], c.Name)
}

// mysqlAutoKey returns the index MySQL needs inline for an AUTO_INCREMENT
// column that is not the primary key ("there can be only one auto column
// and it must be defined as a key"), or nil.
func (g *DDL) mysqlAutoKey(t *Table) *Index {
	if !g.isMySQL() {
		return nil
	}
	for _, c := range t.Columns {
		if !c.AutoIncrement || (t.PrimaryKey != nil && strings.EqualFold(t.PrimaryKey.Columns[0], c.Name)) {
			continue
		}
		for _, i := range t.Indexes {
			if strings.EqualFold(i.Columns[0], c.Name) {
				return i
			}
		}
	}
	return nil
}

func (g *DDL) indexDefinition(i *Index) string {
	if i.Unique {
		return "UNIQUE INDEX " + g.q(i.Name) + " (" + g.qList(i.Columns) + ")"
	}
	return "INDEX " + g.q(i.Name) + " (" + g.qList(i.Columns) + ")"
}

// DefaultConstraintName returns the SQL Server default constraint name.
func DefaultConstraintName(table, column string) string {
	return IdentifierName("df", table, []string{column})
}

// ColumnDeclaration renders "name TYPE [NOT NULL] [DEFAULT ...] ...".
func (g *DDL) ColumnDeclaration(t *Table, c *Column) (string, error) {
	if g.sqliteRowID(t, c) {
		return g.q(c.Name) + " INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL", nil
	}
	if c.AutoIncrement && g.name() == dialect.SQLite {
		return "", fmt.Errorf("schema: SQLite generates values only for an INTEGER PRIMARY KEY, not for %s.%s", t.Name, c.Name)
	}
	typ, err := g.TypeDeclaration(c)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString(g.q(c.Name) + " " + typ)
	if c.AutoIncrement {
		switch g.name() {
		case dialect.Postgres:
			b.WriteString(" GENERATED BY DEFAULT AS IDENTITY")
		case dialect.MSSQL:
			b.WriteString(" IDENTITY(1,1)")
		}
	}
	if c.Nullable {
		b.WriteString(" NULL")
	} else {
		b.WriteString(" NOT NULL")
	}
	if c.AutoIncrement && g.isMySQL() {
		b.WriteString(" AUTO_INCREMENT")
	}
	if c.Default != nil && !c.AutoIncrement {
		if g.name() == dialect.MSSQL {
			b.WriteString(" CONSTRAINT " + g.q(DefaultConstraintName(t.Name, c.Name)))
		}
		b.WriteString(" DEFAULT " + *c.Default)
	}
	if c.Comment != "" && g.isMySQL() {
		b.WriteString(" COMMENT " + g.d.QuoteString(c.Comment))
	}
	return b.String(), nil
}

// CreateTable returns the statements creating t including its indexes.
// Foreign keys are inlined on SQLite (which cannot add them later) and
// returned separately by ForeignKeys for the other databases.
func (g *DDL) CreateTable(t *Table) ([]string, error) {
	stmt, err := g.createTableStmt(t, t.Name)
	if err != nil {
		return nil, err
	}
	out := []string{stmt}
	for _, i := range t.Indexes {
		if i != g.mysqlAutoKey(t) {
			out = append(out, g.CreateIndex(t.Name, i))
		}
	}
	return append(out, g.comments(t)...), nil
}

func (g *DDL) comments(t *Table) []string {
	if g.name() != dialect.Postgres {
		return nil
	}
	var out []string
	if t.Comment != "" {
		out = append(out, g.tableComment(t))
	}
	for _, c := range t.Columns {
		if c.Comment != "" {
			out = append(out, g.columnComment(t.Name, c))
		}
	}
	return out
}

func (g *DDL) tableComment(t *Table) string {
	if g.isMySQL() {
		return "ALTER TABLE " + g.q(t.Name) + " COMMENT = " + g.d.QuoteString(t.Comment)
	}
	val := "NULL"
	if t.Comment != "" {
		val = g.d.QuoteString(t.Comment)
	}
	return "COMMENT ON TABLE " + g.q(t.Name) + " IS " + val
}

// createTableStmt renders CREATE TABLE for t under the given name.
func (g *DDL) createTableStmt(t *Table, name string) (string, error) {
	var defs []string
	for _, c := range t.Columns {
		decl, err := g.ColumnDeclaration(t, c)
		if err != nil {
			return "", err
		}
		defs = append(defs, decl)
	}
	if pk := t.PrimaryKey; pk != nil && !(len(pk.Columns) == 1 && g.sqliteRowID(t, t.Column(pk.Columns[0]))) {
		defs = append(defs, "CONSTRAINT "+g.q(pk.Name)+" PRIMARY KEY ("+g.qList(pk.Columns)+")")
	}
	if g.name() == dialect.SQLite {
		for _, fk := range t.ForeignKeys {
			defs = append(defs, g.foreignKeyDefinition(fk))
		}
	}
	if i := g.mysqlAutoKey(t); i != nil {
		defs = append(defs, g.indexDefinition(i))
	}
	stmt := "CREATE TABLE " + g.q(name) + " (" + strings.Join(defs, ", ") + ")"
	if g.isMySQL() {
		stmt += " DEFAULT CHARACTER SET utf8mb4 COLLATE `utf8mb4_unicode_ci` ENGINE = InnoDB"
		if t.Comment != "" {
			stmt += " COMMENT = " + g.d.QuoteString(t.Comment)
		}
	}
	return stmt, nil
}

func (g *DDL) columnComment(table string, c *Column) string {
	val := "NULL"
	if c.Comment != "" {
		val = g.d.QuoteString(c.Comment)
	}
	return "COMMENT ON COLUMN " + g.q(table) + "." + g.q(c.Name) + " IS " + val
}

// DropTable returns DROP TABLE.
func (g *DDL) DropTable(name string) string { return "DROP TABLE " + g.q(name) }

// CreateIndex returns CREATE [UNIQUE] INDEX. Partial index predicates are
// dropped on MySQL/MariaDB, which do not support them.
func (g *DDL) CreateIndex(table string, i *Index) string {
	s := "CREATE "
	if i.Unique {
		s += "UNIQUE "
	}
	s += "INDEX " + g.q(i.Name) + " ON " + g.q(table) + " (" + g.qList(i.Columns) + ")"
	if i.Where != "" && !g.isMySQL() {
		s += " WHERE " + i.Where
	}
	return s
}

// DropIndex returns DROP INDEX.
func (g *DDL) DropIndex(table string, i *Index) string {
	if g.isMySQL() || g.name() == dialect.MSSQL {
		return "DROP INDEX " + g.q(i.Name) + " ON " + g.q(table)
	}
	return "DROP INDEX " + g.q(i.Name)
}

func (g *DDL) foreignKeyDefinition(fk *ForeignKey) string {
	s := "CONSTRAINT " + g.q(fk.Name) + " FOREIGN KEY (" + g.qList(fk.Columns) + ") REFERENCES " +
		g.q(fk.RefTable) + " (" + g.qList(fk.RefColumns) + ")"
	if fk.OnDelete != NoAction {
		s += " ON DELETE " + string(g.action(fk.OnDelete))
	}
	if fk.OnUpdate != NoAction {
		s += " ON UPDATE " + string(g.action(fk.OnUpdate))
	}
	return s
}

// action maps RESTRICT to NO ACTION on SQL Server, which lacks RESTRICT.
func (g *DDL) action(a Action) Action {
	if a == Restrict && g.name() == dialect.MSSQL {
		return "NO ACTION"
	}
	return a
}

// AddForeignKey returns ALTER TABLE ... ADD CONSTRAINT ... FOREIGN KEY.
// SQLite cannot add constraints to existing tables; ok is false there.
func (g *DDL) AddForeignKey(table string, fk *ForeignKey) (stmt string, ok bool) {
	if g.name() == dialect.SQLite {
		return "", false
	}
	return "ALTER TABLE " + g.q(table) + " ADD " + g.foreignKeyDefinition(fk), true
}

// DropForeignKey returns the statement dropping fk (not possible on SQLite).
func (g *DDL) DropForeignKey(table string, fk *ForeignKey) (stmt string, ok bool) {
	switch {
	case g.name() == dialect.SQLite:
		return "", false
	case g.isMySQL():
		return "ALTER TABLE " + g.q(table) + " DROP FOREIGN KEY " + g.q(fk.Name), true
	default:
		return "ALTER TABLE " + g.q(table) + " DROP CONSTRAINT " + g.q(fk.Name), true
	}
}

// CreateSequence returns CREATE SEQUENCE.
func (g *DDL) CreateSequence(s *Sequence) string {
	stmt := "CREATE SEQUENCE " + g.q(s.Name)
	if g.name() == dialect.MSSQL {
		stmt += " AS BIGINT"
	}
	return stmt + " START WITH " + strconv.FormatInt(s.Start, 10) + " INCREMENT BY " + strconv.FormatInt(s.Increment, 10)
}

// DropSequence returns DROP SEQUENCE.
func (g *DDL) DropSequence(name string) string { return "DROP SEQUENCE " + g.q(name) }

// CreateSchema returns all statements to create s from scratch: sequences,
// tables with indexes, then foreign keys.
func (g *DDL) CreateSchema(s *Schema) ([]string, error) {
	var out []string
	for _, seq := range s.Sequences {
		out = append(out, g.CreateSequence(seq))
	}
	for _, t := range s.Tables {
		stmts, err := g.CreateTable(t)
		if err != nil {
			return nil, err
		}
		out = append(out, stmts...)
	}
	for _, t := range s.Tables {
		for _, fk := range t.ForeignKeys {
			if stmt, ok := g.AddForeignKey(t.Name, fk); ok {
				out = append(out, stmt)
			}
		}
	}
	return out, nil
}

// DropSchema returns statements dropping every table and sequence of s,
// foreign keys first so the order of tables does not matter.
func (g *DDL) DropSchema(s *Schema) []string {
	var out []string
	for _, t := range s.Tables {
		for _, fk := range t.ForeignKeys {
			if stmt, ok := g.DropForeignKey(t.Name, fk); ok {
				out = append(out, stmt)
			}
		}
	}
	for i := len(s.Tables) - 1; i >= 0; i-- {
		out = append(out, g.DropTable(s.Tables[i].Name))
	}
	for _, seq := range s.Sequences {
		out = append(out, g.DropSequence(seq.Name))
	}
	return out
}
