func ddlFor(n dialect.Name) *DDL { return NewDDL(testdialect.Like(n)) }

func blogWithComment() *Schema {
	s := buildBlog()
	s.Table("users").Comment = "people"
	return s
}

func TestCreateSchemaPerDialect(t *testing.T) {
	want := map[dialect.Name][]string{
		dialect.Postgres: {
			`CREATE SEQUENCE "seq" START WITH 1 INCREMENT BY 1`,
			`CREATE TABLE "users" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "email" VARCHAR(180) NOT NULL, "bio" TEXT NULL, "score" NUMERIC(10, 2) NOT NULL DEFAULT 0, "code" CHAR(2) NOT NULL, CONSTRAINT "pk_users" PRIMARY KEY ("id"))`,
			`CREATE UNIQUE INDEX "uniq_users_email" ON "users" ("email")`,
			`COMMENT ON TABLE "users" IS 'people'`,
			`COMMENT ON COLUMN "users"."bio" IS 'about'`,
			`CREATE TABLE "posts" ("id" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL, "author_id" BIGINT NOT NULL, CONSTRAINT "pk_posts" PRIMARY KEY ("id"))`,
			`CREATE INDEX "idx_posts_author_id" ON "posts" ("author_id") WHERE author_id > 0`,
			`ALTER TABLE "posts" ADD CONSTRAINT "fk_posts_author_id" FOREIGN KEY ("author_id") REFERENCES "users" ("id") ON DELETE CASCADE ON UPDATE RESTRICT`,
		},
		dialect.MySQL: {
			"CREATE SEQUENCE `seq` START WITH 1 INCREMENT BY 1",
			"CREATE TABLE `users` (`id` BIGINT NOT NULL AUTO_INCREMENT, `email` VARCHAR(180) NOT NULL, `bio` LONGTEXT NULL COMMENT 'about', `score` DECIMAL(10, 2) NOT NULL DEFAULT 0, `code` CHAR(2) NOT NULL, CONSTRAINT `pk_users` PRIMARY KEY (`id`)) DEFAULT CHARACTER SET utf8mb4 COLLATE `utf8mb4_unicode_ci` ENGINE = InnoDB COMMENT = 'people'",
			"CREATE UNIQUE INDEX `uniq_users_email` ON `users` (`email`)",
			"CREATE TABLE `posts` (`id` BIGINT NOT NULL AUTO_INCREMENT, `author_id` BIGINT NOT NULL, CONSTRAINT `pk_posts` PRIMARY KEY (`id`)) DEFAULT CHARACTER SET utf8mb4 COLLATE `utf8mb4_unicode_ci` ENGINE = InnoDB",
			"CREATE INDEX `idx_posts_author_id` ON `posts` (`author_id`)",
			"ALTER TABLE `posts` ADD CONSTRAINT `fk_posts_author_id` FOREIGN KEY (`author_id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE RESTRICT",
		},
		dialect.SQLite: {
			`CREATE SEQUENCE "seq" START WITH 1 INCREMENT BY 1`,
			`CREATE TABLE "users" ("id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, "email" VARCHAR(180) NOT NULL, "bio" TEXT NULL, "score" DECIMAL(10, 2) NOT NULL DEFAULT 0, "code" CHAR(2) NOT NULL)`,
			`CREATE UNIQUE INDEX "uniq_users_email" ON "users" ("email")`,
			`CREATE TABLE "posts" ("id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, "author_id" BIGINT NOT NULL, CONSTRAINT "fk_posts_author_id" FOREIGN KEY ("author_id") REFERENCES "users" ("id") ON DELETE CASCADE ON UPDATE RESTRICT)`,
			`CREATE INDEX "idx_posts_author_id" ON "posts" ("author_id") WHERE author_id > 0`,
		},
		dialect.MSSQL: {
			`CREATE SEQUENCE [seq] AS BIGINT START WITH 1 INCREMENT BY 1`,
			`CREATE TABLE [users] ([id] BIGINT IDENTITY(1,1) NOT NULL, [email] NVARCHAR(180) NOT NULL, [bio] NVARCHAR(MAX) NULL, [score] DECIMAL(10, 2) NOT NULL CONSTRAINT [df_users_score] DEFAULT 0, [code] NCHAR(2) NOT NULL, CONSTRAINT [pk_users] PRIMARY KEY ([id]))`,
			`CREATE UNIQUE INDEX [uniq_users_email] ON [users] ([email])`,
			`CREATE TABLE [posts] ([id] BIGINT IDENTITY(1,1) NOT NULL, [author_id] BIGINT NOT NULL, CONSTRAINT [pk_posts] PRIMARY KEY ([id]))`,
			`CREATE INDEX [idx_posts_author_id] ON [posts] ([author_id]) WHERE author_id > 0`,
			`ALTER TABLE [posts] ADD CONSTRAINT [fk_posts_author_id] FOREIGN KEY ([author_id]) REFERENCES [users] ([id]) ON DELETE CASCADE ON UPDATE NO ACTION`,
		},
	}
	for n, stmts := range want {
		got, err := ddlFor(n).CreateSchema(blogWithComment())
		if err != nil {
			t.Fatal(err)
		}
		if strings.Join(got, "\n") != strings.Join(stmts, "\n") {
			t.Errorf("%s:\n got:\n%s\nwant:\n%s", n, strings.Join(got, "\n"), strings.Join(stmts, "\n"))
		}
	}
}

func TestDropSchemaPerDialect(t *testing.T) {
	s := buildBlog()
	if got := strings.Join(ddlFor(dialect.MySQL).DropSchema(s), "; "); got !=
		"ALTER TABLE `posts` DROP FOREIGN KEY `fk_posts_author_id`; DROP TABLE `posts`; DROP TABLE `users`; DROP SEQUENCE `seq`" {
		t.Errorf("mysql: %s", got)
	}
	if got := strings.Join(ddlFor(dialect.Postgres).DropSchema(s), "; "); got !=
		`ALTER TABLE "posts" DROP CONSTRAINT "fk_posts_author_id"; DROP TABLE "posts"; DROP TABLE "users"; DROP SEQUENCE "seq"` {
		t.Errorf("pg: %s", got)
	}
	if got := strings.Join(ddlFor(dialect.SQLite).DropSchema(s), "; "); got != `DROP TABLE "posts"; DROP TABLE "users"; DROP SEQUENCE "seq"` {
		t.Errorf("sqlite: %s", got)
	}
}

func TestIndexStatements(t *testing.T) {
	i := &Index{Name: "i", Columns: []string{"a"}}
	if ddlFor(dialect.MSSQL).DropIndex("t", i) != "DROP INDEX [i] ON [t]" || ddlFor(dialect.Postgres).DropIndex("t", i) != `DROP INDEX "i"` {
		t.Fatal("DropIndex")
	}
}

func TestColumnDeclarationVariants(t *testing.T) {
	tbl := &Table{Name: "t"}
	c := &Column{Name: "x", Type: types.Integer, AutoIncrement: true, Default: new(string)}
	if _, err := ddlFor(dialect.SQLite).ColumnDeclaration(tbl, c); err == nil { // no PK: no rowid alias
		t.Fatal("SQLite auto increment outside the primary key")
	}
	raw := &Column{Name: "geo", RawType: "GEOMETRY", Nullable: true}
	if got, _ := ddlFor(dialect.Postgres).ColumnDeclaration(tbl, raw); got != `"geo" GEOMETRY NULL` {
		t.Fatalf("raw = %s", got)
	}
	if _, err := ddlFor(dialect.Postgres).ColumnDeclaration(tbl, &Column{Name: "y", Type: "nope"}); err == nil {
		t.Fatal("unknown type must fail")
	}
	bad := New()
	bad.CreateTable("t").AddColumn("y", "nope")
	if _, err := ddlFor(dialect.Postgres).CreateSchema(bad); err == nil {
		t.Fatal("CreateSchema must propagate errors")
	}
	if g := ddlFor(dialect.Postgres).WithTypes(types.NewRegistry()); g == nil {
		t.Fatal("WithTypes")
	}
	if _, ok := ddlFor(dialect.SQLite).AddForeignKey("t", &ForeignKey{}); ok {
		t.Fatal("sqlite cannot add fks")
	}
	if ddlFor(dialect.Postgres).columnComment("t", &Column{Name: "c"}) != `COMMENT ON COLUMN "t"."c" IS NULL` {
		t.Fatal("empty comment")
	}
}
