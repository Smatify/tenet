func migrateFor(t *testing.T, n dialect.Name, from, to *Schema) []string {
	t.Helper()
	stmts, err := NewDDL(testdialect.Like(n)).MigrateSchemas(from, to, nil)
	if err != nil {
		t.Fatal(err)
	}
	return stmts
}

func expectStmts(t *testing.T, got []string, want ...string) {
	t.Helper()
	if !slices.Equal(got, want) {
		t.Fatalf("\n got:\n  %s\nwant:\n  %s", strings.Join(got, "\n  "), strings.Join(want, "\n  "))
	}
}

func simpleUsers() *Schema {
	s := New()
	u := s.CreateTable("u")
	u.AddColumn("id", types.BigInt).SetAutoIncrement(true)
	u.AddColumn("name", types.String).SetLength(10).SetDefault("'x'")
	u.SetPrimaryKey("id")
	u.AddIndex("name")
	return s
}

func changedUsers() *Schema {
	s := simpleUsers()
	u := s.Table("u")
	u.Column("name").SetLength(20).SetNullable(true).SetDefault("'y'").SetComment("n")
	u.AddColumn("age", types.Integer).SetNullable(true).SetComment("a")
	u.Comment = "users"
	return s
}

func TestMigratePostgres(t *testing.T) {
	expectStmts(t, migrateFor(t, dialect.Postgres, simpleUsers(), changedUsers()),
		`ALTER TABLE "u" ADD COLUMN "age" INTEGER NULL`,
		`ALTER TABLE "u" ALTER COLUMN "name" TYPE VARCHAR(20) USING "name"::VARCHAR(20)`,
		`ALTER TABLE "u" ALTER COLUMN "name" DROP NOT NULL`,
		`ALTER TABLE "u" ALTER COLUMN "name" SET DEFAULT 'y'`,
		`COMMENT ON COLUMN "u"."name" IS 'n'`,
		`COMMENT ON TABLE "u" IS 'users'`,
		`COMMENT ON COLUMN "u"."age" IS 'a'`,
	)
	// identity toggling and default removal
	from, to := simpleUsers(), simpleUsers()
	to.Table("u").Column("id").SetAutoIncrement(false).SetDefault("1")
	to.Table("u").Column("name").Default = nil
	to.Table("u").Column("name").Nullable = false
	expectStmts(t, migrateFor(t, dialect.Postgres, from, to),
		`ALTER TABLE "u" ALTER COLUMN "id" DROP IDENTITY IF EXISTS`,
		`ALTER TABLE "u" ALTER COLUMN "id" SET DEFAULT 1`,
		`ALTER TABLE "u" ALTER COLUMN "name" DROP DEFAULT`,
	)
	expectStmts(t, migrateFor(t, dialect.Postgres, to, from),
		`ALTER TABLE "u" ALTER COLUMN "id" DROP DEFAULT`,
		`ALTER TABLE "u" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY`,
		`ALTER TABLE "u" ALTER COLUMN "name" SET DEFAULT 'x'`,
	)
	nn := simpleUsers()
	nn.Table("u").Column("name").Nullable = true
	expectStmts(t, migrateFor(t, dialect.Postgres, nn, simpleUsers()), `ALTER TABLE "u" ALTER COLUMN "name" SET NOT NULL`)
}

func TestMigrateMySQL(t *testing.T) {
	expectStmts(t, migrateFor(t, dialect.MySQL, simpleUsers(), changedUsers()),
		"ALTER TABLE `u` ADD COLUMN `age` INT NULL COMMENT 'a'",
		"ALTER TABLE `u` MODIFY `name` VARCHAR(20) NULL DEFAULT 'y' COMMENT 'n'",
		"ALTER TABLE `u` COMMENT = 'users'",
	)
}

func TestMigrateMSSQL(t *testing.T) {
	expectStmts(t, migrateFor(t, dialect.MSSQL, simpleUsers(), changedUsers()),
		"DROP INDEX [idx_u_name] ON [u]",
		"ALTER TABLE [u] ADD [age] INT NULL",
		"ALTER TABLE [u] DROP CONSTRAINT [df_u_name]",
		"ALTER TABLE [u] ALTER COLUMN [name] NVARCHAR(20) NULL",
		"ALTER TABLE [u] ADD CONSTRAINT [df_u_name] DEFAULT 'y' FOR [name]",
		"CREATE INDEX [idx_u_name] ON [u] ([name])",
	)
	from, to := simpleUsers(), simpleUsers()
	from.Table("u").Column("name").DefaultName = "DF__u__name__123"
	to.Table("u").DropColumn("name")
	to.Table("u").Indexes = nil
	expectStmts(t, migrateFor(t, dialect.MSSQL, from, to),
		"DROP INDEX [idx_u_name] ON [u]",
		"ALTER TABLE [u] DROP CONSTRAINT [DF__u__name__123]",
		"ALTER TABLE [u] DROP COLUMN [name]",
	)
	to = simpleUsers()
	to.Table("u").Column("id").AutoIncrement = false
	if _, err := NewDDL(testdialect.Like(dialect.MSSQL)).MigrateSchemas(simpleUsers(), to, nil); err == nil {
		t.Fatal("identity change must fail on SQL Server")
	}
}

func TestMigrateOrderAndPrimaryKey(t *testing.T) {
	from := buildBlog()
	to := buildBlog()
	to.DropTable("posts")
	nt := to.CreateTable("comments")
	nt.AddColumn("id", types.Integer)
	nt.AddColumn("user_id", types.BigInt)
	nt.SetPrimaryKey("id")
	nt.AddForeignKey([]string{"user_id"}, "users", []string{"id"})
	to.Table("users").SetPrimaryKey("id", "email")
	to.Sequences[0].Start = 50
	expectStmts(t, migrateFor(t, dialect.Postgres, from, to),
		`ALTER TABLE "posts" DROP CONSTRAINT "fk_posts_author_id"`,
		`DROP SEQUENCE "seq"`,
		`CREATE SEQUENCE "seq" START WITH 50 INCREMENT BY 1`,
		`CREATE TABLE "comments" ("id" INTEGER NOT NULL, "user_id" BIGINT NOT NULL, CONSTRAINT "pk_comments" PRIMARY KEY ("id"))`,
		`ALTER TABLE "users" DROP CONSTRAINT "pk_users"`,
		`ALTER TABLE "users" ADD CONSTRAINT "pk_users" PRIMARY KEY ("id", "email")`,
		`DROP TABLE "posts"`,
		`ALTER TABLE "comments" ADD CONSTRAINT "fk_comments_user_id" FOREIGN KEY ("user_id") REFERENCES "users" ("id")`,
	)
	got := migrateFor(t, dialect.MySQL, from, to)
	if !slices.Contains(got, "ALTER TABLE `users` DROP PRIMARY KEY") || !slices.Contains(got, "ALTER TABLE `users` ADD PRIMARY KEY (`id`, `email`)") {
		t.Fatalf("mysql pk: %v", got)
	}
	gone := buildBlog()
	gone.Sequences = nil
	expectStmts(t, migrateFor(t, dialect.Postgres, buildBlog(), gone), `DROP SEQUENCE "seq"`)
	fk := buildBlog()
	fk.Table("posts").ForeignKeys[0].OnDelete = SetNull
	expectStmts(t, migrateFor(t, dialect.Postgres, buildBlog(), fk),
		`ALTER TABLE "posts" DROP CONSTRAINT "fk_posts_author_id"`,
		`ALTER TABLE "posts" ADD CONSTRAINT "fk_posts_author_id" FOREIGN KEY ("author_id") REFERENCES "users" ("id") ON DELETE SET NULL ON UPDATE RESTRICT`,
	)
}

func TestMigrateSQLite(t *testing.T) {
	// Simple additions use ALTER TABLE.
	from, to := simpleUsers(), simpleUsers()
	to.Table("u").AddColumn("bio", types.Text).SetNullable(true)
	to.Table("u").AddIndex("bio")
	expectStmts(t, migrateFor(t, dialect.SQLite, from, to),
		`ALTER TABLE "u" ADD COLUMN "bio" TEXT NULL`,
		`CREATE INDEX "idx_u_bio" ON "u" ("bio")`,
	)
	// Everything else rebuilds the table.
	expectStmts(t, migrateFor(t, dialect.SQLite, simpleUsers(), changedUsers()),
		`PRAGMA foreign_keys = OFF`,
		`CREATE TABLE "__tmp__u" ("id" INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL, "name" VARCHAR(20) NULL DEFAULT 'y', "age" INTEGER NULL)`,
		`INSERT INTO "__tmp__u" ("id", "name") SELECT "id", "name" FROM "u"`,
		`DROP TABLE "u"`,
		`ALTER TABLE "__tmp__u" RENAME TO "u"`,
		`CREATE INDEX "idx_u_name" ON "u" ("name")`,
		`PRAGMA foreign_keys = ON`,
	)
	for _, mod := range []func(*Table){
		func(t *Table) { t.AddColumn("x", types.Integer) },
		func(t *Table) { t.AddColumn("x", types.DateTime).SetDefault("CURRENT_TIMESTAMP") },
		func(t *Table) { t.AddColumn("x", types.Integer).SetAutoIncrement(true).SetNullable(true) },
		func(t *Table) { t.SetPrimaryKey("id", "name") },
		func(t *Table) { t.AddForeignKey([]string{"name"}, "u", []string{"id"}) },
	} {
		to := simpleUsers()
		mod(to.Table("u"))
		if !sqliteNeedsRebuild(NewComparator(testdialect.Like(dialect.SQLite)).CompareTables(simpleUsers().Table("u"), to.Table("u"))) {
			t.Errorf("expected rebuild for %+v", to.Table("u"))
		}
	}
	// A rebuild of a table without surviving columns has no INSERT.
	empty := New()
	empty.CreateTable("u").AddColumn("old", types.Integer)
	other := New()
	other.CreateTable("u").AddColumn("new", types.Integer)
	got := migrateFor(t, dialect.SQLite, empty, other)
	if slices.ContainsFunc(got, func(s string) bool { return strings.HasPrefix(s, "INSERT") }) {
		t.Fatalf("unexpected insert: %v", got)
	}
}

func TestMigrateErrors(t *testing.T) {
	bad := New()
	bad.CreateTable("x").AddColumn("a", "nope")
	if _, err := NewDDL(testdialect.Like(dialect.Postgres)).MigrateSchemas(New(), bad, nil); err == nil {
		t.Fatal("create with unknown type")
	}
	from := simpleUsers()
	to := simpleUsers()
	to.Table("u").AddColumn("b", "nope")
	for _, n := range []dialect.Name{dialect.Postgres, dialect.SQLite} {
		if _, err := NewDDL(testdialect.Like(n)).MigrateSchemas(from, to, nil); err == nil {
			t.Errorf("%s: add with unknown type", n)
		}
	}
	to = simpleUsers()
	to.Table("u").Column("name").Type = "nope"
	for _, n := range []dialect.Name{dialect.Postgres, dialect.MySQL, dialect.MSSQL, "other"} {
		if _, err := NewDDL(testdialect.Like(n)).MigrateSchemas(from, to, nil); err == nil {
			t.Errorf("%s: change with unknown type", n)
		}
	}
}

