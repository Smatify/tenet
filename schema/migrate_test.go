func TestMySQLAutoIncrementKey(t *testing.T) {
	plain := func() *Schema {
		s := simpleUsers()
		s.Table("u").Column("id").SetAutoIncrement(false) // one auto column per table
		return s
	}
	numbered := func() *Schema {
		s := plain()
		u := s.Table("u")
		u.AddColumn("number", types.BigInt).SetAutoIncrement(true)
		u.AddUniqueIndex("number").SetName("uniq_number")
		return s
	}
	stmts, err := NewDDL(testdialect.Like(dialect.MySQL)).CreateSchema(numbered())
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(stmts[0], "`number` BIGINT NOT NULL AUTO_INCREMENT") || !strings.Contains(stmts[0], "UNIQUE INDEX `uniq_number` (`number`)") ||
		slices.ContainsFunc(stmts, func(s string) bool { return strings.Contains(s, "CREATE UNIQUE INDEX `uniq_number`") }) {
		t.Fatalf("create: %v", stmts)
	}
	got := migrateFor(t, dialect.MySQL, plain(), numbered())
	if !slices.Contains(got, "ALTER TABLE `u` ADD COLUMN `number` BIGINT NOT NULL AUTO_INCREMENT, ADD UNIQUE INDEX `uniq_number` (`number`)") || len(got) != 1 {
		t.Fatalf("alter: %v", got)
	}
}
